CREATE TABLE SERVIZIO (
    ID INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE UTENTE_RUOLO (
    ID_UTENTE INT,
    ID_RUOLO INT,
    PRIMARY KEY (ID_UTENTE, ID_RUOLO),
    FOREIGN KEY (ID_UTENTE) REFERENCES UTENTE(ID) ON DELETE CASCADE,
    FOREIGN KEY (ID_RUOLO) REFERENCES RUOLO(ID) ON DELETE CASCADE
);

CREATE TABLE RUOLO_SERVIZIO (
    ID_RUOLO INT,
    ID_SERVIZIO INT,
    PRIMARY KEY (ID_RUOLO, ID_SERVIZIO),
    FOREIGN KEY (ID_RUOLO) REFERENCES RUOLO(ID) ON DELETE CASCADE,
    FOREIGN KEY (ID_SERVIZIO) REFERENCES SERVIZIO(ID) ON DELETE CASCADE
);
